# ── 把报告里现成的「关注理由」文本 → 问题 key ───────────────────────────
# ⚠️ 用文本反推而不是改 `_fs_risks` 的返回值：那边被 report 多处引用（三元组改动会
#    牵连一堆解包），而这里的文案格式是稳定的（由 `_fs_risks` 固定拼出来）。
import re as _re


def problem_of(reason, kind=None):
    """「关注理由」一句话 → 问题 key；认不出返回 None（宁可不出措施，也不套错）。"""
    t = (reason or "").strip()
    if not t:
        return None
    # ① 互动
    if t.startswith("互动"):
        if "沉默不回复" in t:
            return "interact_silent"
        if "近期沉默" in t:
            return "interact_quiet"
        if "不积极" in t:
            return "interact_passive"
        if "只闲聊" in t:
            return "interact_chat"
        return None
    # ② 小黑板
    if t.startswith("小黑板"):
        if "未提交" in t:
            return "board_blank"
        return None
    if t.startswith("课堂作答"):
        return "board_unfin"
    if "实证错误" in t:
        return "board_hard"
    # ③ 飞书表（`_fs_risks` 的固定句式）
    if _re.search(r"最近连续\s*\d+\s*次未提交", t):
        return "submit_tail"
    if _re.search(r"\d+\s*次全部未交", t):
        return "submit_zero"
    if "呈下滑" in t:
        return "quality_down"
    if "只完成" in t:
        return "submit_item_low"
    if "各项合计提交率" in t:
        return "submit_low"
    if t.startswith("考试") and "偏低" in t:
        return "score_low"
    # ④ 其它
    if "未闭环" in t:
        return "service_open"
    return None

# ── 多个问题同时命中时，先讲哪一个 ────────────────────────────────────
# 依据：① 我们欠的（提问没回）最急，因为拖着会直接影响信任；
#       ② 「最近连续未交」= 人正在掉队，比「一直不太说话」更紧急；
#       ③ 成绩偏低直接决定分层封顶，必须优先解释；
#       ④ 能力型（实证错误）> 参与度型（空白）> 节奏型（没写完）。
PRIORITY = [
    "service_noresp", "service_unresolved", "service_slow", "service_open",
    "submit_tail", "submit_zero", "score_low",
    "board_hard", "submit_low", "submit_item_low", "quality_down", "quality_low",
    "interact_silent", "board_blank", "interact_quiet", "interact_passive", "interact_chat",
    "board_unfin", "attend_issue", "emotion", "interact_noask",
]
_RANK = {k: i for i, k in enumerate(PRIORITY)}


def pick(keys):
    """从命中的问题里挑「先做哪个」+ 其余（按优先级排序）。返回 (main, others)。"""
    ks = [k for k in dict.fromkeys(keys or []) if k in BY_KEY]
    if not ks:
        return None, []
    ks.sort(key=lambda k: _RANK.get(k, 999))
    return ks[0], ks[1:]
