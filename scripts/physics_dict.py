    """知识树统计：(章数, 节数, {年级: (章数, 节数)})。自检 / 文档用。

    ⚠️ 只统计「第X章」条目 —— 必修一的「序言」保留在树里（完整对齐教材），
    但教材口径的「27 章」不含序言。
    """
    tot_ch = tot_sec = 0
    per = {}
    for g in TEXTBOOK_TREE:
        ch = sec = 0
        for b in g["books"]:
            for name, secs in b["chapters"]:
                if "章" not in name:
                    continue
                ch += 1
                sec += len(secs)
        per[g["grade"]] = (ch, sec)
        tot_ch += ch
        tot_sec += sec
    return tot_ch, tot_sec, per


