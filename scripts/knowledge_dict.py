# ── 后台未建、本版不识别（后台补录后自动放回）─────────────────────────────
BACKEND_MISSING = ("立体几何", "导数", "数列", "概率统计")

# ── 后台未建、但按教学口径**保留**的例外（v4.81，用户 2026-10-30 批准）──────
# 用户原话：「目前函数和导数并没有在一起讲，是分开的」。导数是独立一章，若按①剔除，
