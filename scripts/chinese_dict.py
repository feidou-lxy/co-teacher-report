    tot_u = tot_l = 0
    per = {}
    for g in TEXTBOOK_TREE:
        u = l = 0
        for b in g["books"]:
            for _name, lessons in b["units"]:
                u += 1
                l += len(lessons)
        per[g["grade"]] = (u, l)
        tot_u += u
        tot_l += l
    return tot_u, tot_l, per


